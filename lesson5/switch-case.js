let fruit = 'apple';

switch (fruit) {
    case 'banana':
        console.log('It is a banana');
        break;
    case 'apple':
        console.log('It is an apple');
        break;
    case 'pineapple':
        console.log('It is a pineapple');
        break;
    default:
        console.log('It is something else');
}